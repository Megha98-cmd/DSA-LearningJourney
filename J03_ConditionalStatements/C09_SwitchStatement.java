public class C09_SwitchStatement {
    public static void main(String args[]) {
        int number = 2;
        switch (number){
            case 1 : System.out.println("chicken");
            case 2 : System.out.println("coke");
            case 3 : System.out.println("bread");
            default : System.out.println("no food");
        } 
   }
}
